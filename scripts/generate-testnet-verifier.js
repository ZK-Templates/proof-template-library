import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { Barretenberg, UltraHonkBackend } from "@aztec/bb.js";

const root = process.cwd();
const artifact = JSON.parse(await readFile(resolve(root, "artifacts/agent-risk-guard.json"), "utf8"));
const outputPath = resolve(root, "integrations/evm/generated/AgentRiskGuardUltraHonkVerifier.sol");
const api = await Barretenberg.new({ threads: 1 });

try {
  const backend = new UltraHonkBackend(artifact.bytecode, api);
  const verificationKey = await backend.getVerificationKey({ verifierTarget: "evm" });
  const solidity = await backend.getSolidityVerifier(verificationKey, { verifierTarget: "evm" });
  const header = `// Generated by ExpandZK Proof Network Testnet.\n// Testnet reference only. Not audited for production deployment.\n`;
  const normalizedSolidity = solidity.split("\n").map((line) => line.trimEnd()).join("\n");
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `${header}${normalizedSolidity.trim()}\n`);
  console.log(`Generated Solidity verifier at ${outputPath}`);
} finally {
  await api.destroy();
}
